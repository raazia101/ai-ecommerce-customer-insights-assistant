from pathlib import Path

import pandas as pd


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parents[1]

DATA_DIR = BASE_DIR / "data" / "curated"

CUTOFF_DATE = pd.Timestamp("2026-05-24 00:00:00")

PREDICTION_END = pd.Timestamp("2026-08-22 00:00:00")


# ============================================================
# LOAD CURATED DATASETS
# ============================================================

def load_data():
    """
    Load the curated Parquet datasets generated by the
    Week 3 ETL pipeline.
    """

    customers = pd.read_parquet(
        DATA_DIR / "customers.parquet"
    )

    events = pd.read_parquet(
        DATA_DIR / "events.parquet"
    )

    orders = pd.read_parquet(
        DATA_DIR / "orders.parquet"
    )

    order_items = pd.read_parquet(
        DATA_DIR / "order_items.parquet"
    )

    products = pd.read_parquet(
        DATA_DIR / "products.parquet"
    )

    transactions = pd.read_parquet(
        DATA_DIR / "transactions.parquet"
    )

    return (
        customers,
        events,
        orders,
        order_items,
        products,
        transactions,
    )


# ============================================================
# PREPARE DATA TYPES
# ============================================================

def prepare_data(
    customers,
    events,
    orders,
    transactions,
):
    """
    Convert date/time columns into pandas datetime format.
    """

    customers["signup_date"] = pd.to_datetime(
        customers["signup_date"]
    )

    events["timestamp"] = pd.to_datetime(
        events["timestamp"]
    )

    orders["order_date"] = pd.to_datetime(
        orders["order_date"]
    )

    transactions["transaction_date"] = pd.to_datetime(
        transactions["transaction_date"]
    )

    return (
        customers,
        events,
        orders,
        transactions,
    )


# ============================================================
# CREATE ELIGIBLE CUSTOMERS
# ============================================================

def create_eligible_customers(customers):
    """
    Keep only customers who had already signed up
    by the prediction cutoff.

    Customers who signed up after the cutoff could not
    have been part of a prediction made at the cutoff.
    """

    eligible = customers[
        customers["signup_date"] <= CUTOFF_DATE
    ].copy()

    # Number of days the customer had been registered
    # at the prediction cutoff.
    eligible["customer_tenure_days"] = (
        CUTOFF_DATE - eligible["signup_date"]
    ).dt.days

    return eligible


# ============================================================
# CREATE HISTORICAL TRANSACTION FEATURES
# ============================================================

def create_transaction_features(
    eligible_customers,
    transactions,
    orders,
    order_items,
    products,
):
    """
    Create customer-level transaction and purchasing
    behaviour features.

    IMPORTANT:
    Only transaction information available on or before
    the prediction cutoff is used.
    """

    # --------------------------------------------------------
    # HISTORICAL TRANSACTIONS ONLY
    # --------------------------------------------------------

    historical_transactions = transactions[
        transactions["transaction_date"] <= CUTOFF_DATE
    ].copy()

    # --------------------------------------------------------
    # BASE FEATURE DATAFRAME
    # --------------------------------------------------------

    features = eligible_customers[
        ["customer_id"]
    ].copy()

    # --------------------------------------------------------
    # COMPLETED HISTORICAL TRANSACTIONS
    # --------------------------------------------------------

    completed = historical_transactions[
        historical_transactions["status"] == "completed"
    ].copy()

    # --------------------------------------------------------
    # NUMBER OF COMPLETED TRANSACTIONS
    # --------------------------------------------------------

    completed_count = (
        completed
        .groupby("customer_id")
        .size()
        .rename("completed_order_count")
    )

    features = features.merge(
        completed_count,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # TOTAL COMPLETED REVENUE
    # --------------------------------------------------------

    completed_revenue = (
        completed
        .groupby("customer_id")["amount"]
        .sum()
        .rename("completed_revenue")
    )

    features = features.merge(
        completed_revenue,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # AVERAGE COMPLETED ORDER VALUE
    # --------------------------------------------------------

    features["average_order_value"] = (
        features["completed_revenue"]
        / features["completed_order_count"]
    )

    # --------------------------------------------------------
    # LAST COMPLETED PURCHASE
    # --------------------------------------------------------

    last_purchase = (
        completed
        .groupby("customer_id")["transaction_date"]
        .max()
        .rename("last_purchase_date")
    )

    features = features.merge(
        last_purchase,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # DAYS SINCE LAST PURCHASE
    # --------------------------------------------------------

    features["days_since_last_purchase"] = (
        CUTOFF_DATE
        - features["last_purchase_date"]
    ).dt.days

    # --------------------------------------------------------
    # WHETHER CUSTOMER HAS A PREVIOUS PURCHASE
    # --------------------------------------------------------

    # This is important because a missing last_purchase_date
    # means something different from "purchased today".

    features["has_previous_purchase"] = (
        features["last_purchase_date"]
        .notna()
        .astype(int)
    )

    # --------------------------------------------------------
    # TOTAL HISTORICAL TRANSACTIONS
    # --------------------------------------------------------

    total_transactions = (
        historical_transactions
        .groupby("customer_id")
        .size()
        .rename("total_transaction_count")
    )

    features = features.merge(
        total_transactions,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # FAILED TRANSACTIONS
    # --------------------------------------------------------

    failed = historical_transactions[
        historical_transactions["status"] == "failed"
    ]

    failed_count = (
        failed
        .groupby("customer_id")
        .size()
        .rename("failed_transaction_count")
    )

    features = features.merge(
        failed_count,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # REFUNDED TRANSACTIONS
    # --------------------------------------------------------

    refunded = historical_transactions[
        historical_transactions["status"] == "refunded"
    ]

    refunded_count = (
        refunded
        .groupby("customer_id")
        .size()
        .rename("refunded_transaction_count")
    )

    features = features.merge(
        refunded_count,
        on="customer_id",
        how="left",
    )

    # ========================================================
    # PRODUCT-LEVEL PURCHASE FEATURES
    # ========================================================

    # Find orders associated with historical completed
    # transactions.

    completed_order_ids = (
        completed["order_id"]
        .dropna()
        .unique()
    )

    completed_orders = orders[
        orders["order_id"].isin(completed_order_ids)
        & (
            orders["order_date"]
            <= CUTOFF_DATE
        )
    ].copy()

    # --------------------------------------------------------
    # ORDERS → ORDER ITEMS
    # --------------------------------------------------------

    historical_items = order_items.merge(
        completed_orders[
            ["order_id", "customer_id"]
        ],
        on="order_id",
        how="inner",
    )

    # --------------------------------------------------------
    # ORDER ITEMS → PRODUCTS
    # --------------------------------------------------------

    historical_items = historical_items.merge(
        products[
            ["product_id", "category"]
        ],
        on="product_id",
        how="left",
    )

    # --------------------------------------------------------
    # UNIQUE PRODUCTS PURCHASED
    # --------------------------------------------------------

    unique_products = (
        historical_items
        .groupby("customer_id")["product_id"]
        .nunique()
        .rename("unique_products_purchased")
    )

    features = features.merge(
        unique_products,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # UNIQUE CATEGORIES PURCHASED
    # --------------------------------------------------------

    unique_categories = (
        historical_items
        .groupby("customer_id")["category"]
        .nunique()
        .rename("unique_categories_purchased")
    )

    features = features.merge(
        unique_categories,
        on="customer_id",
        how="left",
    )

    return features


# ============================================================
# CREATE HISTORICAL EVENT FEATURES
# ============================================================

def create_event_features(
    eligible_customers,
    events,
):
    """
    Create customer-level engagement features from events.

    Only events occurring on or before the prediction cutoff
    are included.
    """

    # --------------------------------------------------------
    # HISTORICAL EVENTS ONLY
    # --------------------------------------------------------

    historical_events = events[
        events["timestamp"] <= CUTOFF_DATE
    ].copy()

    # --------------------------------------------------------
    # BASE FEATURE DATAFRAME
    # --------------------------------------------------------

    features = eligible_customers[
        ["customer_id"]
    ].copy()

    # --------------------------------------------------------
    # TOTAL EVENTS
    # --------------------------------------------------------

    total_events = (
        historical_events
        .groupby("customer_id")
        .size()
        .rename("total_event_count")
    )

    features = features.merge(
        total_events,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # EVENT-SPECIFIC COUNTS
    # --------------------------------------------------------

    event_types = [
        "product_view",
        "add_to_cart",
        "checkout_started",
        "search",
        "login",
        "purchase",
        "remove_from_cart",
    ]

    for event_type in event_types:

        event_count = (
            historical_events[
                historical_events["event_type"] == event_type
            ]
            .groupby("customer_id")
            .size()
            .rename(
                f"{event_type}_count"
            )
        )

        features = features.merge(
            event_count,
            on="customer_id",
            how="left",
        )

    return features


# ============================================================
# CREATE FUTURE TARGET
# ============================================================

def create_target(
    eligible_customers,
    transactions,
):
    """
    Create the binary repeat-purchase target.

    Target = 1:
        Customer makes at least one completed transaction
        during the future prediction window.

    Target = 0:
        Customer makes no completed transaction during
        the future prediction window.

    IMPORTANT:
    Future transaction data is used ONLY for the target.
    It must never be used as a model feature.
    """

    # --------------------------------------------------------
    # FUTURE COMPLETED TRANSACTIONS
    # --------------------------------------------------------

    future_completed = transactions[
        (transactions["transaction_date"] > CUTOFF_DATE)
        & (
            transactions["transaction_date"]
            <= PREDICTION_END
        )
        & (
            transactions["status"] == "completed"
        )
    ].copy()

    # --------------------------------------------------------
    # CUSTOMERS WITH FUTURE COMPLETED PURCHASE
    # --------------------------------------------------------

    future_customers = (
        future_completed["customer_id"]
        .drop_duplicates()
    )

    # --------------------------------------------------------
    # CREATE TARGET DATAFRAME
    # --------------------------------------------------------

    target = eligible_customers[
        ["customer_id"]
    ].copy()

    target["repeat_purchase"] = (
        target["customer_id"]
        .isin(future_customers)
        .astype(int)
    )

    return target


# ============================================================
# BUILD FINAL ML DATASET
# ============================================================

def build_ml_dataset():

    # --------------------------------------------------------
    # LOAD DATA
    # --------------------------------------------------------

    (
        customers,
        events,
        orders,
        order_items,
        products,
        transactions,
    ) = load_data()

    # --------------------------------------------------------
    # PREPARE DATA
    # --------------------------------------------------------

    (
        customers,
        events,
        orders,
        transactions,
    ) = prepare_data(
        customers,
        events,
        orders,
        transactions,
    )

    # --------------------------------------------------------
    # ELIGIBLE CUSTOMERS
    # --------------------------------------------------------

    eligible_customers = (
        create_eligible_customers(
            customers
        )
    )

    # --------------------------------------------------------
    # TRANSACTION FEATURES
    # --------------------------------------------------------

    transaction_features = (
        create_transaction_features(
            eligible_customers,
            transactions,
            orders,
            order_items,
            products,
        )
    )

    # --------------------------------------------------------
    # EVENT FEATURES
    # --------------------------------------------------------

    event_features = (
        create_event_features(
            eligible_customers,
            events,
        )
    )

    # --------------------------------------------------------
    # TARGET
    # --------------------------------------------------------

    target = create_target(
        eligible_customers,
        transactions,
    )

    # ========================================================
    # START FINAL DATASET
    # ========================================================

    ml_dataset = eligible_customers[
        [
            "customer_id",
            "country",
            "status",
            "customer_tenure_days",
        ]
    ].copy()

    # --------------------------------------------------------
    # ADD TRANSACTION FEATURES
    # --------------------------------------------------------

    ml_dataset = ml_dataset.merge(
        transaction_features,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # ADD EVENT FEATURES
    # --------------------------------------------------------

    ml_dataset = ml_dataset.merge(
        event_features,
        on="customer_id",
        how="left",
    )

    # --------------------------------------------------------
    # ADD TARGET
    # --------------------------------------------------------

    ml_dataset = ml_dataset.merge(
        target,
        on="customer_id",
        how="left",
    )

    # ========================================================
    # HANDLE MISSING AGGREGATE FEATURES
    # ========================================================

    # For count/revenue features:
    # missing means the customer had zero occurrences.

    zero_fill_columns = [
        "completed_order_count",
        "completed_revenue",
        "average_order_value",
        "total_transaction_count",
        "failed_transaction_count",
        "refunded_transaction_count",
        "unique_products_purchased",
        "unique_categories_purchased",
        "total_event_count",
        "product_view_count",
        "add_to_cart_count",
        "checkout_started_count",
        "search_count",
        "login_count",
        "purchase_count",
        "remove_from_cart_count",
    ]

    ml_dataset[zero_fill_columns] = (
        ml_dataset[zero_fill_columns]
        .fillna(0)
    )

    # IMPORTANT:
    #
    # days_since_last_purchase is intentionally NOT filled
    # with zero.
    #
    # NaN means the customer has never made a completed
    # purchase before the prediction cutoff.

    # ========================================================
    # SAVE DATASET
    # ========================================================

    output_path = (
        DATA_DIR
        / "ml_customer_features.parquet"
    )

    ml_dataset.to_parquet(
        output_path,
        index=False,
    )

    return ml_dataset


